def check(section: str, label: str, got, want, tol: float = 0.005) -> None:
    """Assert one claim. Numeric comparisons use an absolute tolerance."""
    if isinstance(want, (int, float, np.integer, np.floating)) and not isinstance(want, bool):
        ok = abs(float(got) - float(want)) <= tol
        detail = f"got {float(got):,.4f}  want {float(want):,.4f}"
    else:
        ok = got == want
        detail = f"got {got!r}  want {want!r}"
    _results.append((section, label, ok, detail))


