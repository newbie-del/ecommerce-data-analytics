# RFM in SQL vs pandas. Exact equality is NOT expected - NTILE and qcut break
# ties differently - so the aggregate is asserted and the drift is reported.
sql_rfm = pd.read_sql_query("""
    WITH per_customer AS (
        SELECT customer_key, MIN(order_date) AS first_order_date,
               MAX(order_date) AS last_order_date,
               COUNT(DISTINCT order_key) AS frequency, SUM(revenue) AS monetary
        FROM fact_order_lines GROUP BY customer_key),
    scored AS (
        SELECT c.*, 6 - NTILE(5) OVER (ORDER BY c.last_order_date DESC) AS r_score,
               NTILE(5) OVER (ORDER BY c.frequency ASC) AS f_score,
               NTILE(5) OVER (ORDER BY c.monetary ASC)  AS m_score
        FROM per_customer c)
    SELECT CASE
        WHEN first_order_date >= '2014-10-02' THEN 'New Customers'
        WHEN r_score >= 4 AND (f_score + m_score) / 2.0 >= 4 THEN 'Champions'
        WHEN r_score >= 3 AND (f_score + m_score) / 2.0 >= 3 THEN 'Loyal Customers'
        WHEN r_score >= 3 THEN 'Potential Loyalists'
        WHEN r_score = 2 THEN 'At Risk'
        ELSE 'Lost Customers' END AS segment_name,
        COUNT(*) AS customers
    FROM scored GROUP BY segment_name
""", con).set_index("segment_name")["customers"]
check(S, "SQL RFM covers all 795 customers", int(sql_rfm.sum()), 795)
check(S, "SQL RFM also yields an empty New Customers segment",
      int(sql_rfm.get("New Customers", 0)), 0)
