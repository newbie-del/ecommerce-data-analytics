def strip_sql_comments(sql: str) -> str:
    """Remove -- comments while respecting single-quoted string literals.

    Necessary because several comments in these files legitimately contain
    semicolons (and 00_schema.sql has a commented-out LOAD DATA statement), so a
    naive split(';') would produce fragments that are not valid SQL.
    """
    result: list[str] = []
    in_string = False
    i = 0
    while i < len(sql):
        ch = sql[i]
        if in_string:
            result.append(ch)
            if ch == "'":
                if i + 1 < len(sql) and sql[i + 1] == "'":
                    result.append(sql[i + 1])
                    i += 2
                    continue
                in_string = False
            i += 1
            continue
        if ch == "'":
            in_string = True
            result.append(ch)
            i += 1
            continue
        if ch == "-" and i + 1 < len(sql) and sql[i + 1] == "-":
            newline = sql.find("\n", i)
            if newline == -1:
                break
            i = newline
            continue
        result.append(ch)
        i += 1
    return "".join(result)


def split_statements(sql: str) -> list[str]:
    return [s.strip() for s in strip_sql_comments(sql).split(";") if s.strip()]


